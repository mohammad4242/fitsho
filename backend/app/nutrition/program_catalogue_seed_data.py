from dataclasses import dataclass
from uuid import UUID

from app.nutrition.enums import MealCategory, NutritionBudgetTier, NutritionDietStyle


@dataclass(frozen=True)
class CanonicalMeal:
    id: UUID
    category: MealCategory
    name_fa: str


def meal(meal_id: str, category: MealCategory, name_fa: str) -> CanonicalMeal:
    return CanonicalMeal(UUID(meal_id), category, name_fa)


