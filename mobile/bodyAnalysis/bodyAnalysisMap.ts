function bilateralMask(file: string, d: string): BodyMapVisualMask {
  return {
    file,
    paths: [
      { d },
      { d, transform: MIRROR_TRANSFORM },
    ],
  };
}

function singleMask(file: string, d: string): BodyMapVisualMask {
  return { file, paths: [{ d }] };
}

